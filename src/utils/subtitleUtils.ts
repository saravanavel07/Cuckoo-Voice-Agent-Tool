import { SubtitleSegment } from '../types';

export function formatTimeSRT(seconds: number): string {
  const pad = (n: number, z = 2) => ('00' + n).slice(-z);
  const hrs = Math.floor(seconds / 3600);
  const mins = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);
  const millis = Math.floor((seconds % 1) * 1000);
  return `${pad(hrs)}:${pad(mins)}:${pad(secs)},${pad(millis, 3)}`;
}

export function formatTimeVTT(seconds: number): string {
  const pad = (n: number, z = 2) => ('00' + n).slice(-z);
  const hrs = Math.floor(seconds / 3600);
  const mins = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);
  const millis = Math.floor((seconds % 1) * 1000);
  return `${pad(hrs)}:${pad(mins)}:${pad(secs)}.${pad(millis, 3)}`;
}

export function formatTimeDisplay(seconds: number): string {
  const mins = Math.floor(seconds / 60);
  const secs = Math.floor(seconds % 60);
  return `${mins}:${secs < 10 ? '0' : ''}${secs}`;
}

export function generateSRT(segments: SubtitleSegment[]): string {
  return segments
    .filter((s) => s.text.trim().length > 0)
    .map((seg, idx) => {
      const speakerPrefix = seg.speaker ? `[${seg.speaker}] ` : '';
      return `${idx + 1}\n${formatTimeSRT(seg.start)} --> ${formatTimeSRT(seg.end)}\n${speakerPrefix}${seg.text.trim()}\n`;
    })
    .join('\n');
}

export function generateVTT(segments: SubtitleSegment[]): string {
  const body = segments
    .filter((s) => s.text.trim().length > 0)
    .map((seg, idx) => {
      const speakerPrefix = seg.speaker ? `<v ${seg.speaker}>` : '';
      const speakerSuffix = seg.speaker ? `</v>` : '';
      return `${idx + 1}\n${formatTimeVTT(seg.start)} --> ${formatTimeVTT(seg.end)}\n${speakerPrefix}${seg.text.trim()}${speakerSuffix}\n`;
    })
    .join('\n');

  return `WEBVTT - Generated by CUCKOO VOICE AI\n\n${body}`;
}

export function generateJSON(sessionText: string, segments: SubtitleSegment[], metadata: any): string {
  return JSON.stringify(
    {
      app: 'CUCKOO VOICE AI',
      exportedAt: new Date().toISOString(),
      metadata,
      transcript: sessionText,
      segments,
    },
    null,
    2
  );
}

export function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
